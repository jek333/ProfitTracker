    fun describe(code: String): String {
        val normalized = code.uppercase().take(5)
        known[normalized]?.let { return it }
        return group(normalized)
    }

    /** Whether [describe] returns an exact definition rather than a group description. */
    fun isKnown(code: String): Boolean = code.uppercase().take(5) in known

    private fun group(code: String): String {
        if (code.length < 5) return "Unknown code"
        val system = code[0]
        val generic = code[1] == '0' || (system == 'P' && code[1] == '2') || (system == 'U' && code[1] == '0')
        val prefix = if (generic) "Generic" else "Manufacturer-specific"
        val area = when (system) {
            'P' -> when (code[2]) {
                '0', '1', '2' -> "fuel and air metering"
                '3' -> "ignition system or misfire"
                '4' -> "auxiliary emission controls"
                '5' -> "vehicle speed, idle control or auxiliary inputs"
                '6' -> "computer or output circuits"
                '7', '8', '9' -> "transmission"
                'A', 'B', 'C' -> "hybrid propulsion"
                else -> "powertrain"
            }
            'C' -> "chassis (brakes, steering, suspension)"
            'B' -> "body (airbags, lighting, comfort)"
            'U' -> "network communication"
            else -> "system"
        }
        return "$prefix $area fault"
    }
